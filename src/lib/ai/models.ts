export function getModelById(modelId: string, preferredProvider?: ProviderId): ModelCapability | undefined {
  if (preferredProvider) {
    const match = VERIFIED_MODELS.find((m) => m.id === modelId && m.provider === preferredProvider);
    if (match) return match;
  }
  return VERIFIED_MODELS.find((m) => m.id === modelId);
}

export function getModelsByProvider(provider: ProviderId): ModelCapability[] {
  return VERIFIED_MODELS.filter((m) => m.provider === provider);
}

export function getFallbackForModel(model: ModelCapability): {
  targetModelId: string;
  targetProvider: ProviderId;
} | null {
  if (model.fallbackModelId && model.fallbackProvider) {
    return {
      targetModelId: model.fallbackModelId,
      targetProvider: model.fallbackProvider,
    };
  }

  if (model.provider === 'radox') {
    return { targetModelId: 'intern-latest', targetProvider: 'inkstone' };
  } else {
    return { targetModelId: 'gpt-5.6-luna', targetProvider: 'radox' };
  }
}

/**
 * Every model that a tier may use. A model is available when the tier of the
 * account is equal to or higher than the `minTier` of the model.
 */
export function getModelsForTier(tier: number): ModelCapability[] {
  return VERIFIED_MODELS.filter((m) => (m.minTier ?? 0) <= tier);
}

/**
 * The models of a tier, grouped by provider. Used by the model selector and
 * by the API that serves the catalogue.
 */
export function getModelsForTierByProvider(
  tier: number
): Record<ProviderId, ModelCapability[]> {
  const grouped: Record<ProviderId, ModelCapability[]> = { radox: [], inkstone: [] };
  for (const model of getModelsForTier(tier)) {
    grouped[model.provider].push(model);
  }
  return grouped;
}
