import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { BUILTIN_SKILLS } from './builtins';

/**
 * The skills live in Supabase only - the migrations are the source of truth for
 * the seeded rows. This test guarantees the SQL seeds and the TypeScript
 * built-in library never drift apart.
 *
 * The catalogue is seeded by two migrations:
 *   - 20261020000000_agent_skills.sql          -> schema + the original 12 skills
 *   - 20261024000000_agent_skills_expansion.sql -> the full catalogue (28 skills)
 *
 * The second one is generated by `node scripts/generate-skill-migration.js`
 * and is the canonical seed: it re-seeds every built-in skill, so the database
 * always matches src/lib/skills/builtins.ts.
 */
const BASE_MIGRATION = '20261020000000_agent_skills.sql';
const EXPANSION_MIGRATION = '20261024000000_agent_skills_expansion.sql';

function readMigration(fileName: string): string {
  return readFileSync(join(process.cwd(), 'supabase', 'migrations', fileName), 'utf8');
}

/** Extracts the slugs used by the idempotent seed of a migration. */
function extractSeededSlugs(sql: string): string[] {
  // Every seeded row starts with "( null, '<slug>', '<name>', ...".
  const pattern = /\(\s*null,\s*'([a-z0-9]+(?:-[a-z0-9]+)*)'/g;
  const slugs = new Set<string>();
  let match: RegExpExecArray | null;

  while ((match = pattern.exec(sql)) !== null) {
    slugs.add(match[1]);
  }

  return Array.from(slugs);
}

/** Extracts the body of a seeded skill (the dollar quoted content). */
function extractSeededBody(sql: string, slug: string): string | null {
  const pattern = new RegExp(
    `\\(\\s*null,\\s*'${slug}',[\\s\\S]{0,4000}?\\$body\\$([\\s\\S]*?)\\$body\\$,`,
    'i'
  );
  const match = sql.match(pattern);
  if (!match) return null;

  // Single quotes are escaped in SQL by doubling them.
  return match[1].replace(/''/g, "'");
}

describe('skills migration', () => {
  const baseSql = readMigration(BASE_MIGRATION);
  const expansionSql = readMigration(EXPANSION_MIGRATION);
  const allSql = `${baseSql}\n${expansionSql}`;

  it('creates the skills table', () => {
    expect(baseSql).toMatch(/create table if not exists public\.skills/i);
    expect(baseSql).toMatch(/user_id/);
    expect(baseSql).toMatch(/is_pinned/);
    expect(baseSql).toMatch(/is_active/);
  });

  it('enables row level security', () => {
    expect(baseSql).toMatch(/alter table public\.skills enable row level security/i);
    expect(baseSql).toMatch(/create policy/i);
  });

  it('is idempotent (the seed can run more than once)', () => {
    for (const sql of [baseSql, expansionSql]) {
      expect(sql).toMatch(/on conflict/i);
      expect(sql).toMatch(/where user_id is null/i);
    }
  });

  it('seeds exactly the skills of the built-in library', () => {
    const seeded = extractSeededSlugs(allSql).sort();
    const builtin = BUILTIN_SKILLS.map((skill) => skill.slug).sort();

    expect(seeded).toEqual(builtin);
  });

  it('seeds the whole catalogue in the expansion migration', () => {
    const seeded = extractSeededSlugs(expansionSql).sort();
    const builtin = BUILTIN_SKILLS.map((skill) => skill.slug).sort();

    expect(seeded).toEqual(builtin);
  });

  it('never seeds the same skill twice inside a migration', () => {
    for (const sql of [baseSql, expansionSql]) {
      const rows = sql.match(/\(\s*null,\s*'[a-z0-9-]+'/g) ?? [];
      expect(new Set(rows).size).toBe(rows.length);
    }
  });

  it('keeps the slug of every built-in skill unique', () => {
    const slugs = BUILTIN_SKILLS.map((skill) => skill.slug);
    expect(new Set(slugs).size).toBe(slugs.length);
  });

  it('gives every built-in skill a description and a body', () => {
    for (const skill of BUILTIN_SKILLS) {
      expect(skill.name.length).toBeGreaterThan(0);
      expect(skill.description.length).toBeGreaterThan(10);
      expect(skill.content.length).toBeGreaterThan(100);
      expect(skill.category.length).toBeGreaterThan(0);
    }
  });

  it('seeds the same body as the TypeScript built-in library', () => {
    for (const skill of BUILTIN_SKILLS) {
      const seeded = extractSeededBody(expansionSql, skill.slug);
      const normalizedSeeded = seeded?.replace(/\r\n/g, '\n');
      const normalizedContent = skill.content.replace(/\r\n/g, '\n');
      expect(normalizedSeeded, `body of ${skill.slug} drifted from the SQL seed`).toBe(normalizedContent);
    }
  });

  it('seeds the same metadata as the TypeScript built-in library', () => {
    for (const skill of BUILTIN_SKILLS) {
      const pattern = new RegExp(
        `\\(\\s*null,\\s*'${skill.slug}',[\\s\\S]{0,4000}?\\$body\\$[\\s\\S]*?\\$body\\$,\\s*'${skill.category}',\\s*'${skill.icon}',\\s*array\\[[^\\]]*\\],\\s*'${skill.kind}',\\s*true,\\s*false,\\s*${skill.sortOrder}`,
        'i'
      );
      expect(allSql, `skill ${skill.slug} is missing from the SQL seed`).toMatch(pattern);
    }
  });
});
